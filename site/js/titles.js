/** @param {string} lang @param {string | null | undefined} id @returns {Title | null} */
export function titleById(lang, id) {
  if (!id) return null;
  return byIdIndex(lang).get(id) || null;
}

/** id → Title の索引 (言語ごと)。一覧の配列が差し替わるか件数が変わったら作り直す (テストが一覧に足すため)
 * Worker の title_sync は 1 回に 500 人 × 数百の id を確かめるので、毎回一覧を頭から探すと重い
 * @type {Map<string, { list: Title[], n: number, map: Map<string, Title> }>} */
const BY_ID = new Map();
/** @param {string} lang */
function byIdIndex(lang) {
  const list = TITLES[lang] || [];
  let c = BY_ID.get(lang);
  if (!c || c.list !== list || c.n !== list.length) {
    c = { list, n: list.length, map: new Map(list.map(t => [t.id, t])) };
    BY_ID.set(lang, c);
  }
  return c.map;
}

/** FNV-1a (32 bit)。UTF-16 の単位で回す (ページでも Worker でも同じ値) @param {string} s */
export function hash32(s) {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h >>> 0;
}

/** @typedef {{ date?: string, event_id?: number | string, parent_event_id?: number | string | null, wins?: number, losses?: number }} TourRow */

/** 下位クラスの仮想大会 (本戦の中の B〜E クラス。parent_event_id = 本戦) か @param {TourRow} t */
const isClassRow = t => !(t.parent_event_id == null || t.parent_event_id === '');

/** 1 試合以上した行 (本戦・下位クラスとも)。日付・ID の順 @param {TourRow[]} tournaments @returns {TourRow[]} */
function playedRows(tournaments) {
  return (tournaments || [])
    .filter(t => t && t.date && ((t.wins || 0) + (t.losses || 0)) >= 1)
    .slice()
    .sort((a, b) => (String(a.date) < String(b.date) ? -1 : String(a.date) > String(b.date) ? 1 : String(a.event_id).localeCompare(String(b.event_id))));
}

/** 数える大会 = 本戦で 1 試合以上したもの (下位クラスの仮想大会は本戦と同じ日の同じ大会なので数えない)。日付・ID の順
 * @param {TourRow[]} tournaments */
export function countedTournaments(tournaments) {
  return playedRows(tournaments).filter(t => !isClassRow(t));
}

/** 選手ごとの引く順番 (ownedTitles の中身)。ランダム解放の二つ名を「選手 ID・二つ名 ID」のハッシュの小さい順に並べ、
 * 前半 / 後半の技名 / 後半の技名以外の 3 つの列に分ける。抽選はその列の先頭から「その日に引けて、まだ持っていない」ものを取る。
 * 並べるのは選手ごとに 1 回だけなので、抽選の回数が多くても一覧を何度も見直さない
 * @param {Title[]} list @param {number | string} uid */
function drawQueues(list, uid) {
  /** @type {{ t: Title, h: number }[]} */
  const xs = [];
  for (const t of list) if (t.unlock === 'random') xs.push({ t, h: hash32(`${uid}|${t.id}`) });
  xs.sort((a, b) => a.h - b.h || (a.t.id < b.t.id ? -1 : 1));
  /** @type {{ items: Title[], start: number }[]} */
  const [pre, move, other] = [{ items: [], start: 0 }, { items: [], start: 0 }, { items: [], start: 0 }];
  for (const { t } of xs) {
    if (usableIn(t, 'pre')) pre.items.push(t);
    if (usableIn(t, 'post')) (t.kind === 'move' ? move : other).items.push(t);
  }
  return { pre, move, other };
}

/** 列の先頭から、その日 (at) に引けて、まだ持っていないもの。先頭の持っているものは読み飛ばした位置を覚える
 * @param {{ items: Title[], start: number }} q @param {Map<string, OwnedTitle>} owned @param {string} at @returns {Title | null} */
function takeFrom(q, owned, at) {
  while (q.start < q.items.length && owned.has(q.items[q.start].id)) q.start++;
  for (let i = q.start; i < q.items.length; i++) {
    const t = q.items[i];
    if (owned.has(t.id) || t.added > at || (t.retired && t.retired <= at)) continue;
    return t;
  }
  return null;
}

/** その選手が持っている二つ名。uid = start.gg のユーザー ID
 * @param {string} lang @param {number | string} uid @param {{ date?: string, event_id?: number | string, parent_event_id?: number | string | null, wins?: number, losses?: number }[]} tournaments
 * @param {TitleProfile} [profile]
 * @returns {Map<string, OwnedTitle>} */
export function ownedTitles(lang, uid, tournaments, profile) {
  const list = TITLES[lang] || [];
  const chars = new Set(((profile && profile.chars) || []).map(String));
  const pref = (profile && profile.pref) || null;
  /** @type {Map<string, OwnedTitle>} */
  const owned = new Map();
  for (const t of list) {
    if (t.unlock === 'initial') owned.set(t.id, { at: TITLE_LAUNCH, how: 'initial' });
    else if (t.retired) continue;   // キャラ・都道府県のもの: 廃止後は新しく持たない (持っていた人は記録 title_owned に残る)
    else if (t.unlock === 'char' && (t.chars || []).some(c => chars.has(String(c)))) owned.set(t.id, { at: TITLE_LAUNCH, how: 'char' });
    else if (t.unlock === 'pref' && pref && t.pref === pref) owned.set(t.id, { at: TITLE_LAUNCH, how: 'pref' });
  }
  /** @param {'pre' | 'post'} side @param {string} key @param {string} at @param {OwnedTitle['how']} how */
  const qs = drawQueues(list, uid);
  const draw = (side, key, at, how) => {
    let best;
    if (side === 'pre') best = takeFrom(qs.pre, owned, at);
    else {
      // 後半: 技名か否かを MOVE_SHARE で決める (ハッシュの上の位。FNV-1a の下の位は文字の偶奇に引きずられるので使わない)。片方が尽きたらもう片方
      const wantMove = hash32(`${uid}|${key}|kind`) < 0x100000000 / MOVE_SHARE.den * MOVE_SHARE.num;
      const [first, second] = wantMove ? [qs.move, qs.other] : [qs.other, qs.move];
      best = takeFrom(first, owned, at) || takeFrom(second, owned, at);
    }
    if (best) owned.set(best.id, { at, how });
  };
  for (let i = 1; i <= INITIAL_DRAWS.pre; i++) draw('pre', `pre|start|${i}`, TITLE_LAUNCH, 'start');
  for (let i = 1; i <= INITIAL_DRAWS.post; i++) draw('post', `post|start|${i}`, TITLE_LAUNCH, 'start');
  let nPre = 0, nPost = 0, matches = 0;
  // 前半は本戦の行だけ、後半の試合数は下位クラスの試合も足す (2026-10-14 ユーザー決定)
  for (const t of playedRows(tournaments)) {
    const at = String(t.date).slice(0, 10);
    if (at < TITLE_LAUNCH) continue;
    if (!isClassRow(t)) for (let i = 0; i < PRE_PER_TOURNAMENT; i++) draw('pre', `pre|${++nPre}`, at, 'random');
    matches += (t.wins || 0) + (t.losses || 0);
    while (nPost < Math.floor(matches / POST_PER_MATCHES.matches) * POST_PER_MATCHES.posts) draw('post', `post|${++nPost}`, at, 'random');
  }
  return owned;
}

// ── 持っている二つ名の記録 (D1 title_owned.bits、docs/card_titles_design.md「持っている二つ名の記録」) ──
// ビット列 = 二つ名の通し番号 (id の 4 桁、ja-0001 → 1) を位置にしたもの。位置 n は (n >> 3) バイト目の (n & 7) ビット目 (下位から)。
// base64url (詰め物の = なし) の文字列で持つ。空 ("") = 何も持っていない。ページ・Worker・記録の処理で同じ関数を使う

/** id の通し番号 (ja-0123 → 123)。形が違えば null @param {string} id @returns {number | null} */
export function titleNumber(id) {
  const m = /^[a-z]{2}-(\d{4})$/.exec(String(id || ''));
  return m ? Number(m[1]) : null;
}

/** @param {string} bits @returns {Uint8Array} */
function bitsBytes(bits) {
  const b64 = String(bits || '').replace(/-/g, '+').replace(/_/g, '/');
  if (!b64) return new Uint8Array(0);
  const bin = atob(b64 + '='.repeat((4 - (b64.length % 4)) % 4));
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
}

/** 末尾の 0 のバイトは落とす (同じ中身なら同じ文字列) @param {Uint8Array} bytes @returns {string} */
function bytesBits(bytes) {
  let n = bytes.length;
  while (n > 0 && bytes[n - 1] === 0) n--;
  let bin = '';
  for (let i = 0; i < n; i++) bin += String.fromCharCode(bytes[i]);
  return n ? btoa(bin).replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '') : '';
}

/** id の並びからビット列 (形の違う id は無視) @param {Iterable<string>} ids @returns {string} */
export function bitsFromIds(ids) {
  /** @type {number[]} */
  const nums = [];
  for (const id of ids || []) { const n = titleNumber(id); if (n !== null) nums.push(n); }
  const bytes = new Uint8Array(nums.length ? (Math.max(...nums) >> 3) + 1 : 0);
  for (const n of nums) bytes[n >> 3] |= 1 << (n & 7);
  return bytesBits(bytes);
}

/** ビット列にその id があるか @param {string} bits @param {string} id */
export function bitsHas(bits, id) {
  const n = titleNumber(id);
  if (n === null) return false;
  const bytes = bitsBytes(bits);
  return (n >> 3) < bytes.length && (bytes[n >> 3] & (1 << (n & 7))) !== 0;
}

/** 2 つのビット列の OR @param {string} a @param {string} b @returns {string} */
export function bitsOr(a, b) {
  const x = bitsBytes(a), y = bitsBytes(b);
  const out = new Uint8Array(Math.max(x.length, y.length));
  for (let i = 0; i < out.length; i++) out[i] = (x[i] || 0) | (y[i] || 0);
  return bytesBits(out);
}

/** ビット列の通し番号 (昇順) @param {string} bits @returns {number[]} */
export function bitsNumbers(bits) {
  const bytes = bitsBytes(bits);
  /** @type {number[]} */
  const out = [];
  for (let i = 0; i < bytes.length; i++) for (let j = 0; j < 8; j++) if (bytes[i] & (1 << j)) out.push(i * 8 + j);
  return out;
}

/** ビット列の二つ名 (その言語の一覧にあるものだけ) @param {string} lang @param {string} bits @returns {Title[]} */
export function bitsTitles(lang, bits) {
  // ビット列は 1 回だけ読む (二つ名ごとに bitsHas すると一覧の件数だけ読み直す)
  const idx = byIdIndex(lang);
  /** @type {Title[]} */
  const out = [];
  for (const n of bitsNumbers(bits)) {
    const t = idx.get(`${lang}-${String(n).padStart(4, '0')}`);
    if (t) out.push(t);
  }
  return out;
}

/** 選手のファイル (players/<uid>.json) から持っている二つ名。正本は記録 (D1) で、ビルドが title_bits として写したもの。
 * 記録がまだ無い (同期前・新しい人) ときだけ、出た大会から計算する。最初から持っているものは常に含む
 * @param {string} lang @param {number | string} uid @param {any} player @param {TitleProfile} [profile] @returns {Map<string, { at: string, how: string }>} */
export function ownedFromPlayer(lang, uid, player, profile) {
  const bits = player && typeof player.title_bits === 'string' ? player.title_bits : null;
  if (bits === null) return ownedTitles(lang, uid, (player && player.tournaments) || [], profile);
  /** @type {Map<string, { at: string, how: string }>} */
  const m = new Map();
  for (const t of TITLES[lang] || []) if (t.unlock === 'initial') m.set(t.id, { at: '', how: 'initial' });
  for (const t of bitsTitles(lang, bits)) m.set(t.id, { at: player.title_updated || '', how: 'record' });
  return m;
}

